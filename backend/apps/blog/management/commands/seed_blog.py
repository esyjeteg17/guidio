class Command(BaseCommand):
    help = "Заполняет блог демонстрационными статьями"

    def add_arguments(self, parser):
        parser.add_argument(
            "--reset",
            action="store_true",
            help="Удалить все существующие статьи перед добавлением",
        )

    def handle(self, *args, **options):
        if options["reset"]:
            deleted, _ = Article.objects.all().delete()
            self.stdout.write(f"Удалено существующих статей: {deleted}")

        created = 0
        skipped = 0
        for data in ARTICLES:
            obj, was_created = Article.objects.get_or_create(
                title=data["title"],
                defaults=data,
            )
            if was_created:
                created += 1
            else:
                skipped += 1

        self.stdout.write(self.style.SUCCESS(
            f"Создано: {created}, уже было: {skipped}, всего в БД: {Article.objects.count()}"
        ))
